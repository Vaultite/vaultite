const CHEVRON = '<path d="m9 18 6-6-6-6"/>'
const ALIASES: Record<string, string> = {
  summary: "abstract", tldr: "abstract", hint: "tip", important: "tip", check: "success", done: "success",
  help: "question", faq: "question", caution: "warning", attention: "warning", fail: "failure", missing: "failure",
  error: "danger", cite: "quote",
}
export const CALLOUT = /^\[!([\w-]+)\]([+-]?)[ \t]*([^\n]*)(?:\n|$)/

function calloutType(name: string) {
  const n = name.toLowerCase()
  const type = ALIASES[n] ?? n
  return ICONS[type] ? type : n
}

export function calloutHtml(name: string, fold: string, title: string, content: string) {
  const type = calloutType(name)
  const head = `<span class="callout-icon">${svg(ICONS[type] ?? ICONS.note)}</span><span class="callout-title-text">${title}</span>`
  const inner = content ? `<div class="callout-content">${content}</div>` : ""
  if (!fold) return `<div class="callout" data-callout="${esc(type)}"><div class="callout-title">${head}</div>${inner}</div>\n`
  return `<details class="callout" data-callout="${esc(type)}"${fold === "+" ? " open" : ""}><summary class="callout-title">${head}` +
    `<span class="callout-fold">${svg(CHEVRON)}</span></summary>${inner}</details>\n`
}
