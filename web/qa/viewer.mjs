  await page.keyboard.press("ControlOrMeta+0")
  check("…and back with ⌘0", near(await pageBox(), w0), [w0, await pageBox()])
  await ctx.close()

  const phone = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true }), p = watch(await phone.newPage()), pui = app(p), popen = opened(p, pui)
  const f = await fingers(p)
  const touch = (type, pts) => f.cdp.send("Input.dispatchTouchEvent", { type, touchPoints: pts.map(([x, y], id) => ({ x, y, id })) })
  const pinch = async (x, y, from, to) => {
    await touch("touchStart", [[x - from, y]]); await touch("touchStart", [[x - from, y], [x + from, y]])
    for (let i = 1; i <= 10; i++) { const d = from + ((to - from) * i) / 10; await touch("touchMove", [[x - d, y], [x + d, y]]) }
    await touch("touchEnd", [])
  }
  const tap = async (x, y) => { await touch("touchStart", [[x, y]]); await touch("touchEnd", []) }
  await popen("Map.png")
  await until(async () => (await view(p))?.w > 100)
  const pfit = await view(p), [px, py] = middle(pfit)
  check("phone: all of it, as wide as the screen", near(pfit.w, 390 - 24) && !pfit.zoomed, pfit)
  await f.swipe(60, py, 330, py + 4); await pui.idle()
  check("phone: all of it shown, a swipe is still the app's (the sidebar)", await until(async () => (await view(p)).box.x > 50 || await p.locator("[data-phone-drawer]").count() > 0), await view(p))
  await popen("Map.png")
  await until(async () => (await view(p))?.w > 100)
  await pinch(px, py, 40, 130)
  const pin = await view(p)
  check("phone: a pinch zooms in, the page still", pin.zoomed && pin.w > pfit.w * 2.5 && await p.evaluate(() => scrollY === 0 && visualViewport.scale === 1), pin)
  await f.swipe(300, py + 60, 160, py - 60)
  const pan = await view(p)
  check("phone: zoomed, a finger pans it and opens nothing", near(pan.x, pin.x - 140, 12) && near(pan.y, pin.y - 120, 12) && near(pan.box.x, pfit.box.x), { pin, pan })
  await pinch(px, py, 150, 20)
  check("phone: pinched out, all of it again", !(await view(p)).zoomed)
  await tap(px, py); await tap(px, py)
  check("phone: a double tap zooms in", await until(async () => (await view(p)).percent === 100), await view(p))
  await p.screenshot({ path: `${OUT}viewer-phone.png` })
  await popen("Pictures.md")
  await p.locator(".cm-image").first().tap(); await pui.idle()
  check("phone: a tap on a note's image opens the viewer, no keyboard", p.url().includes("/viewer/") && await p.evaluate(() => !document.activeElement?.closest(".cm-editor")), p.url())
  await p.locator("[data-sheet-done]").click(); await pui.idle()
  check("phone: Done closes it", !p.url().includes("/viewer/"))
  await phone.close()
