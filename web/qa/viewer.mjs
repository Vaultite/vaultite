  const dragged = await view(page)
  check("a drag pans, and isn't a click", near(dragged.x, inAt.x - 150) && near(dragged.y, inAt.y - 90) && dragged.zoomed, { inAt, dragged })
  await page.mouse.wheel(0, 70)
  check("zoomed, a wheel pans", near((await view(page)).y, dragged.y - 70), await view(page))
  const before = under(await view(page), cx, cy)
  await page.keyboard.down("Control"); await page.mouse.wheel(0, 100); await page.keyboard.up("Control")
  const out = await view(page), after = under(out, cx - 150, cy - 90)
  check("a pinch (Control + wheel) zooms about the pointer", out.percent < 90 && out.percent > 70 && near(under(out, cx - 150, cy - 90)[0], after[0], 0.01) && before.length === 2, out)
  for (let i = 0; i < 40; i++) await page.mouse.wheel(400, 400)
  const end = await view(page)
  check("panned to its last corner, it stops clear of the status bar", near(end.x + end.w, end.box.w - 28) && near(end.y + end.h, end.box.h - 28), end)
  await page.keyboard.press("Shift+Digit1")
  check("Shift+1: all of it", !(await view(page)).zoomed)
  await page.keyboard.press("Shift+Digit2")
  check("Shift+2: its width", near((await view(page)).w, fit.box.w), await view(page))
  await page.keyboard.press("Shift+Digit0")
  check("Shift+0: its own size", (await view(page)).percent === 100)
  await page.keyboard.press("Minus")
  check("-: a step out", (await view(page)).percent === 80)
  await page.keyboard.press("Equal")
  check("=: a step in, stopping at 100%", (await view(page)).percent === 100)
  const still = await view(page)
  await page.keyboard.press("ArrowDown")
  check("arrows pan", (await view(page)).y < still.y - 50, await view(page))
  await page.keyboard.press("ControlOrMeta+Equal")
  check("⌘+ zooms it, not the app", (await view(page)).percent === 125)
  await page.locator("[data-zoom-tool='Zoom to fit']").click()
  check("its buttons: Zoom to fit", !(await view(page)).zoomed)
  await page.mouse.dblclick(cx, cy)
  check("a double click zooms in once", (await view(page)).percent === 100)
  await page.setViewportSize({ width: 1100, height: 760 }); await ui.idle()
  const resized = await view(page)
  check("the window resized, it keeps its zoom", resized.percent === 100 && resized.zoomed, resized)
  await page.setViewportSize({ width: 1280, height: 860 }); await ui.idle()
  await page.screenshot({ path: `${OUT}viewer-image.png` })
  await open("Plan.svg")
  await until(async () => (await view(page))?.w > 100)
  check("a small SVG is shown as large as its pane", near((await view(page)).w, (await view(page)).box.w - 56), await view(page))

  await open("Pictures.md")
  await page.locator(".cm-image").first().waitFor()
  await until(() => page.locator(".cm-block-mermaid svg.pele").count())
