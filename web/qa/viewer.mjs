  await until(async () => (await view(page))?.w > 100)
  const sheet = await view(page)
  check("a note's image, clicked while editing: the viewer, its Markdown as it was", page.url().includes(`/viewer/${enc(`${DIR}/Map.png`)}`) && !sheet.zoomed && sheet.box.w > 1100 && await page.locator(".is-source").count() === 0, sheet)
  await page.mouse.click(...middle(sheet))
  check("…zoomed as in its tab", (await view(page)).percent === 100)
  await page.keyboard.press("ControlOrMeta+Minus")
  check("…and by its keys", (await view(page)).percent === 80)
  await page.screenshot({ path: `${OUT}viewer-sheet.png` })
  await page.getByRole("button", { name: "Open in new tab" }).click(); await ui.idle()
  check("…opened in a tab from there", page.url().endsWith(enc(`${DIR}/Map.png`)) && await page.locator("dialog[open]").count() === 0, page.url())
  await open("Pictures.md")
  await until(() => page.locator(".cm-block-mermaid svg.pele").count())
