  const pageBox = () => page.evaluate(() => document.querySelector("[data-docx]")?.shadowRoot?.querySelector("section.docx")?.getBoundingClientRect().width ?? 0)
  await until(async () => await pageBox() > 0, 8000)
  const w0 = await pageBox()
  await page.mouse.move(700, 300); await page.keyboard.down("Control"); await page.mouse.wheel(0, -100); await page.mouse.wheel(0, -100); await page.keyboard.up("Control")
