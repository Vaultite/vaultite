// Docked notes edited as tabs are (DockedFile.tsx, FileView.tsx, editor/mirror.ts, core/active.ts, core/autosave.ts, panelDrop.ts, PhoneDrawer.tsx). WRITES "Qa docked/", sidebars, appearance (put back): throwaway only.   node web/qa/dockednotes.mjs <base url> <vault path> [out dir]
import { mkdirSync, readFileSync } from "node:fs"
import { SHOTS, apiAt, qa, until, viewsAt } from "./lib/qa.mjs"
import { app } from "./lib/app.mjs"
const { args: [B, VAULT, OUT = SHOTS], browser, check, watch, done } = await qa(import.meta.url)
mkdirSync(OUT, { recursive: true })
const api = apiAt(B)
const DIR = "Qa docked", SIDE = `${DIR}/Side.md`, OTHER = `${DIR}/Other.md`, KEY = `pages:file/${SIDE}`
const put = (path, text) => api("PUT", "file", { path, text, base: null })
const read = (p) => { try { return readFileSync(`${VAULT}/${p}`, "utf8") } catch { return "" } }
const saved = async (test, p = SIDE) => !!(await until(() => test(read(p)), 6000))

await fetch(`${B}api/file?path=${encodeURIComponent(DIR)}`, { method: "DELETE" })
await put(SIDE, "# Side\n\nDocked note with **bold** and a [[Other]] link.\n\n## Part\n\nLast line.\n")
await put(OTHER, "Other note.\n")
const sidebarsBefore = await api("GET", "config/sidebars"), lookBefore = await api("GET", "config/appearance")
for (const n of [1, 2, 3, 4, 5]) await fetch(new URL(`/api/workspaces/${n}`, B), { method: "DELETE" })
await api("PUT", "config/sidebars", { left: ["files:files"], right: ["outline:outline", KEY], collapsed: [], heights: {} })

const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 2 })
const page = watch(await ctx.newPage()), ui = app(page)
const panel = page.locator(`[data-panel="${KEY}"]`)
const docked = panel.locator(".cm-content")
const dockedLine = (text) => panel.locator(".cm-line", { hasText: text }).first()
const mainText = page.locator("#main-scroll .vau-editor .cm-content")
await page.goto(`${B}#file/${encodeURIComponent(OTHER)}`)
await dockedLine("Last line.").waitFor({ timeout: 15000 }); await ui.idle()

check("a docked note is the tab's editor, editable (live preview by default)", await docked.getAttribute("contenteditable") === "true" && await panel.locator(".cm-line", { hasText: "bold" }).locator(".cm-strong, strong, [class*=strong]").count() > 0)
check("…its first heading shown, the panel's heading naming it", await panel.locator(".cm-h1", { hasText: "Side" }).count() === 1)
await dockedLine("Last line.").click(); await page.keyboard.press("End")
await page.keyboard.type(" Typed here, g i too.")
check("typed in: saved to the file", await saved((t) => t.includes("Last line. Typed here, g i too.\n")), read(SIDE))
check("…single keys typed, not run as shortcuts (G I is the inbox's)", !/#inbox|view:inbox/.test(page.url()) && (await ui.pane.all()).join() === "Other", [page.url(), await ui.pane.all()])
await ui.idle()
await page.screenshot({ path: `${OUT}docked-note-editing.png` })

await dockedLine("Docked note").click({ button: "right" })
await page.locator("[role=menu]").last().waitFor()
const items = await ui.menu.items()
check("right-click on its text: the editor's menu, not the panel's", items.includes("Copy link to block") && !items.some((i) => /^Panels|in a tab$/.test(i)), items)
await page.keyboard.press("Escape"); await ui.idle()

await dockedLine("Part").click()
await page.keyboard.press("ControlOrMeta+e"); await ui.idle()
check("⌘E with the keyboard in it: its view switches to reading, the tab's doesn't", await until(async () => await docked.getAttribute("contenteditable") === "false") && await mainText.getAttribute("contenteditable") === "true")
await panel.locator("[data-panel-handle]").hover()
await panel.locator("[data-docked-view]").click(); await ui.idle()
check("its heading's button switches it back to editing", await until(async () => await docked.getAttribute("contenteditable") === "true"))
await mainText.click(); await page.keyboard.press("ControlOrMeta+e"); await ui.idle()
check("⌘E in the tab switches the tab's view only", await until(async () => await mainText.getAttribute("contenteditable") === "false") && await docked.getAttribute("contenteditable") === "true")
await page.keyboard.press("ControlOrMeta+e"); await ui.idle()

const row = (p) => page.locator(`aside [role=tree] div[data-tree-path="${p}"]`).first()
if (!(await row(SIDE).isVisible().catch(() => false))) { await row(DIR).click(); await row(SIDE).waitFor() }
await row(SIDE).click()
const tabLine = (text) => page.locator("#main-scroll .cm-line", { hasText: text }).first()
await tabLine("Last line.").waitFor(); await ui.idle()
await tabLine("Last line.").click(); await page.keyboard.press("End")
await page.keyboard.type(" From the tab.")
check("the same note in a tab: typed there, the docked one shows it as it's typed", await until(async () => /From the tab\./.test(await dockedLine("Last line.").innerText()), 1500), await dockedLine("Last line.").innerText())
await dockedLine("Docked note").click(); await page.keyboard.press("End")
await page.keyboard.type(" From the dock.")
check("…and typed in the docked one, the tab shows it", await until(async () => /From the dock\./.test(await tabLine("Docked note").innerText()), 1500), await tabLine("Docked note").innerText())
check("…both saved, once each", await saved((t) => t.split("From the dock.").length === 2 && t.split("From the tab.").length === 2), read(SIDE))
await ui.saved()
const said = await page.locator("main, aside").evaluateAll((els) => els.map((e) => e.innerText).join("\n"))
check("…with no conflict in either", !/while you typed|changed elsewhere/.test(said))

async function drag(from, to, at = "end") {
  const f = await from.boundingBox(), t = await to.boundingBox()
  const [fx, fy] = [f.x + 30, f.y + f.height / 2], tx = at === "end" ? t.x + t.width - 4 : t.x + 40, ty = t.y + t.height / 2
  await page.mouse.move(fx, fy); await page.mouse.down(); await page.mouse.move(fx + 8, fy + 4, { steps: 2 })
  await page.mouse.move(tx, ty, { steps: 10 }); await ui.idle()
  const caret = await page.locator(".cm-file-drop").count()
  await page.mouse.up(); await ui.idle()
  return caret
}
await row(OTHER).click(); await page.locator("#main-scroll .cm-line", { hasText: "Other note." }).waitFor(); await ui.idle()
const layout = JSON.stringify(await api("GET", "config/sidebars"))
const caret = await drag(row(OTHER), dockedLine("Part"))
check("a file dragged onto a docked note's text: a caret where it goes", caret === 1, caret)
check("…dropped: its link there, the sidebar's panels as they were", await saved((t) => t.includes("Part[[Other]]\n")) && JSON.stringify(await api("GET", "config/sidebars")) === layout, [read(SIDE), await api("GET", "config/sidebars")])
await drag(row(OTHER), panel.locator("[data-panel-handle]").first(), "start")
const docks = async () => (await api("GET", "config/sidebars")).right ?? []
check("dropped on its heading, it's docked there as a panel", await until(async () => (await docks()).includes(`pages:file/${OTHER}`), 4000), await docks())
check("…the docked note's text as it was", !read(SIDE).includes("Part[[Other]][[Other]]"), read(SIDE))
await api("POST", "ops/panel.hide", { panel: OTHER })
await until(async () => !(await docks()).includes(`pages:file/${OTHER}`), 4000)

await row(SIDE).click(); await tabLine("Last line.").waitFor(); await ui.idle()
await panel.locator(".cm-line", { hasText: "Docked note" }).locator("text=Other").first().click()
check("a link clicked in it opens in the main area", await until(async () => (await ui.pane.all()).join() === "Other", 4000) && await panel.count() === 1, await ui.pane.all())

const lines = Array.from({ length: 80 }, (_, i) => `Line ${i + 1} of a long docked note.`).join("\n")
await ui.sees(SIDE, () => put(SIDE, `# Side\n\n${lines}\n`))
await dockedLine("Line 3 of").waitFor(); await ui.idle()
const box = () => page.evaluate((key) => {
  const p = document.querySelector(`[data-panel="${CSS.escape(key)}"]`), sc = p.querySelector("[data-panel-scroll]"), body = p.closest("[data-sidebar-body]")
  return { own: sc.scrollHeight > sc.clientHeight + 4, ownTop: sc.scrollTop, mode: body.dataset.scroll, body: body.scrollHeight > body.clientHeight + 4, bodyTop: body.scrollTop }
}, KEY)
await dockedLine("Line 3 of").click(); await page.keyboard.press("ControlOrMeta+End"); await page.keyboard.type(" End.")
check("panels scrolling on their own: the long note scrolls in its panel, to the cursor", await until(async () => { const b = await box(); return b.mode === "panels" && b.own && b.ownTop > 0 }, 3000), await box())
check("…and what's typed at its end is saved", await saved((t) => /Line 80 of a long docked note\.\n? End\.\n?$/.test(t)), read(SIDE).slice(-60))
await page.screenshot({ path: `${OUT}docked-note-panel-scroll.png` })
await api("PATCH", "config/appearance", { sidebarScroll: "sidebar" })
await until(async () => (await box()).mode === "sidebar", 5000)
await page.keyboard.press("ControlOrMeta+Home"); await page.keyboard.press("ControlOrMeta+End"); await ui.idle()
check("the sidebar scrolling as one: the whole sidebar scrolls to the cursor", await until(async () => { const b = await box(); return b.body && b.bodyTop > 0 && !b.own }, 3000), await box())

await ctx.close()

await api("PATCH", "config/appearance", { sidebarScroll: lookBefore.sidebarScroll ?? null })
await put(SIDE, "# Side\n\nOn the phone.\n")
const phoneCtx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true })
const P = watch(await phoneCtx.newPage()), pui = app(P)
await P.goto(`${B}#file/${encodeURIComponent(OTHER)}`); await pui.idle()
await P.locator("[data-phone-header] button[aria-label='Open right sidebar']").tap(); await pui.idle()
const phoneLine = P.locator(`[data-phone-drawer] [data-panel="${KEY}"] .cm-line`, { hasText: "On the phone." }).first()
const phoneText = P.locator(`[data-phone-drawer] [data-panel="${KEY}"] .cm-content`)
await phoneLine.waitFor({ timeout: 8000 })
check("phone: a docked note opens in reading view, as a phone's tab does", await phoneText.getAttribute("contenteditable") === "false")
await viewsAt(B)("live")
await P.reload(); await pui.idle()
await P.locator("[data-phone-header] button[aria-label='Open right sidebar']").tap(); await pui.idle()
await phoneLine.waitFor({ timeout: 8000 })
check("…and in editing once tabs open in editing", await phoneText.getAttribute("contenteditable") === "true")
await phoneLine.tap(); await P.keyboard.press("End"); await P.keyboard.type(" Typed in the drawer.")
check("phone: the docked note in the right drawer is edited there and saved", await saved((t) => t.includes("On the phone. Typed in the drawer.\n")), read(SIDE))
check("…the drawer still open", await P.locator("[data-phone-drawer=right]").count() === 1)
await pui.idle()
await P.screenshot({ path: `${OUT}docked-note-phone.png` })
await phoneCtx.close()
await viewsAt(B)(null)
await api("PUT", "config/sidebars", sidebarsBefore)
await api("PATCH", "config/appearance", { sidebarScroll: lookBefore.sidebarScroll ?? null })
await fetch(`${B}api/file?path=${encodeURIComponent(DIR)}`, { method: "DELETE" })
await done()
